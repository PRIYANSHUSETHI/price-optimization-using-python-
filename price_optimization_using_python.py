"""Price Recommendation Engine Using Elasticity"""

def recommend_price(row):
    if pd.isna(row['elasticity']):
        return row['Price']
    elif row['elasticity'] < -1:
        return row['Price'] * 0.95  # decrease by 5%
    elif row['elasticity'] > -1 and row['elasticity'] < 0:
        return row['Price'] * 1.05  # increase by 5%
    else:
        return row['Price']

data['recommended_price'] = data.apply(recommend_price, axis=1)

