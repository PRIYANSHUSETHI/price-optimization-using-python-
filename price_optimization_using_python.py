"""A/B Testing Simulation for Dynamic vs Static Prices"""

def ab_test_simulation(data, test_fraction=0.3):
    test_group = data.sample(frac=test_fraction, random_state=42)
    control_group = data.drop(test_group.index)

    test_group['ab_price'] = test_group['recommended_price']
    control_group['ab_price'] = control_group['Price']

    test_group['ab_sales'] = test_group['ab_price'] * test_group['Item_Quantity']
    control_group['ab_sales'] = control_group['ab_price'] * control_group['Item_Quantity']

    summary = pd.DataFrame({
        'Group': ['Control', 'Test'],
        'Total Sales': [control_group['ab_sales'].sum(), test_group['ab_sales'].sum()],
        'Average Sales per Item': [control_group['ab_sales'].mean(), test_group['ab_sales'].mean()]
    })
    return summary

