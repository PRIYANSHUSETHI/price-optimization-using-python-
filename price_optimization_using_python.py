"""Scenario Simulator Tool"""

# Sample elasticity (use segment/item-specific value if available)
avg_elasticity = data['elasticity'].mean()

# Create a range of price changes
price_changes = np.arange(-0.3, 0.31, 0.05)  # -30% to +30%

# Reference price and cost (assume one item or mean values)
base_price = data['Price'].mean()
cost = base_price * 0.6  # Assuming 40% margin

sim_results = []

for change in price_changes:
    new_price = base_price * (1 + change)
    pct_qty_change = avg_elasticity * change
    new_qty = data['Item_Quantity'].mean() * (1 + pct_qty_change)
    revenue = new_price * new_qty
    profit = (new_price - cost) * new_qty
    sim_results.append({
        'Price Change (%)': round(change * 100),
        'New Price': new_price,
        'Expected Quantity': new_qty,
        'Revenue': revenue,
        'Profit': profit
    })

scenario_df = pd.DataFrame(sim_results)

# Plot Revenue and Profit vs Price Change
